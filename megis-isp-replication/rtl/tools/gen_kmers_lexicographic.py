from itertools import product

# DNA alphabet in required order
dna = ['A', 'C', 'G', 'T']
k = 5

# Generate all 1024 k-mers in lexicographic order
kmers = [''.join(p) for p in product(dna, repeat=k)]

# Split into 4 columns
col1 = kmers[0:256]
col2 = kmers[256:512]
col3 = kmers[512:768]
col4 = kmers[768:1024]

# Print as 4 columns row-wise
for i in range(256):
    print(col1[i], col2[i], col3[i], col4[i])