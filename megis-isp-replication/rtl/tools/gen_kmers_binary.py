from itertools import product

# DNA alphabet and binary encoding
dna = ['A', 'C', 'G', 'T']
bin_map = {
    'A': '00',
    'C': '01',
    'G': '10',
    'T': '11'
}

k = 5

# Generate all k-mers
kmers = [''.join(p) for p in product(dna, repeat=k)]

# Split by last base
colA = [k for k in kmers if k[-1] == 'A']
colC = [k for k in kmers if k[-1] == 'C']
colG = [k for k in kmers if k[-1] == 'G']
colT = [k for k in kmers if k[-1] == 'T']

# Function to convert k-mer to binary
def kmer_to_bin(kmer):
    return ''.join(bin_map[b] for b in kmer)

# Print all rows
for i in range(len(colA)):
    print(
        f"{kmer_to_bin(colA[i])}\t"
        f"{kmer_to_bin(colC[i])}\t"
        f"{kmer_to_bin(colG[i])}\t"
        f"{kmer_to_bin(colT[i])}"
    )