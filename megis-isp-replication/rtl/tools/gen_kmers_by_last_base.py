from itertools import product

dna = ['A', 'C', 'G', 'T']
k = 5

# Generate all k-mers in lexicographic order
kmers = [''.join(p) for p in product(dna, repeat=k)]

# Split by last base
col1 = [k for k in kmers if k[-1] == 'A']
col2 = [k for k in kmers if k[-1] == 'C']
col3 = [k for k in kmers if k[-1] == 'G']
col4 = [k for k in kmers if k[-1] == 'T']

# Print everything till the end
for i in range(len(col1)):
    print(f"{col1[i]}\t{col2[i]}\t{col3[i]}\t{col4[i]}")